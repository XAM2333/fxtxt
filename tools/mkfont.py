"""Convert the Casio DLF fonts into C tables for the FXTXT add-in.

Layout discovered from the files (verified glyph-by-glyph):
  * glyph index = (qu - 1) * 94 + (wei - 1) for GB2312 codes 0xA0+qu / 0xA0+wei
  * FONT8 : 8 rows of 1 byte per glyph (8x8), FONT12 : 12 rows of 2 bytes (12x12)
  * the ASCII range 0x21..0x7E sits at glyph 188..281 (GB2312 qu 3), stored as
    narrow 8-px cells

Outputs (into work/fxtxt/src):
  font_ascii.c  95 glyphs x 8 / 24 bytes, bracket glyphs repaired
  font_cjk.c    all glyphs from both DLF files
  gb2312_map.c  sorted Unicode -> glyph index table for UTF-8 input
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "work", "fxtxt", "src")
BASE = 0x24
ASCII_GLYPH0 = 188          # glyph of '!' in both fonts

FIX8 = {
    "(": [0x10, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x10],
    ")": [0x20, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x20],
    "[": [0x30, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20, 0x30],
    "]": [0x30, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x30],
    "{": [0x30, 0x20, 0x20, 0x40, 0x20, 0x20, 0x30, 0x00],
    "}": [0x30, 0x10, 0x10, 0x08, 0x10, 0x10, 0x30, 0x00],
    "<": [0x00, 0x10, 0x20, 0x40, 0x20, 0x10, 0x00, 0x00],
    ">": [0x00, 0x10, 0x08, 0x04, 0x08, 0x10, 0x00, 0x00],
}


def scale_to12(rows8):
    out = []
    for y in range(12):
        src = rows8[min(7, y * 8 // 12)]
        v = 0
        for x in range(12):
            sx = min(7, x * 8 // 12)
            if (src >> (7 - sx)) & 1:
                v |= 1 << (11 - x)
        out.append(((v << 4) >> 8) & 0xFF)
        out.append(((v << 4) & 0xFF))
    return out


def write_array(path, decl, rows, comment_fn, per_line=8):
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/mkfont.py - do not edit. */\n")
        f.write('#include "font.h"\n\n')
        f.write(decl + " = {\n")
        for i, row in enumerate(rows):
            body = ", ".join("0x%02X" % b for b in row)
            note = comment_fn(i) if comment_fn else ""
            f.write("\t/* %s */ { %s },\n" % (note, body) if note else "\t{ %s },\n" % body)
        f.write("};\n")
    print("wrote", path, len(rows), "entries")


def main():
    f8 = open(os.path.join(ROOT, "FONT8.dlf"), "rb").read()
    f12 = open(os.path.join(ROOT, "FONT12.dlf"), "rb").read()
    n8 = (len(f8) - BASE) // 8
    n12 = (len(f12) - BASE) // 24
    n = min(n8, n12)
    print("glyph counts", n8, n12, "-> using", n)

    # --- ASCII table (0x20..0x7E) with repaired brackets
    ascii8, ascii12, fixed = [], [], 0
    for code in range(0x20, 0x7F):
        gi = ASCII_GLYPH0 + (code - 0x21)
        g8 = list(f8[BASE + gi * 8: BASE + gi * 8 + 8])
        g12 = list(f12[BASE + gi * 24: BASE + gi * 24 + 24])
        if chr(code) in FIX8:
            g8 = FIX8[chr(code)]
            g12 = scale_to12(g8)
            fixed += 1
        ascii8.append(g8)
        ascii12.append(g12)

    write_array(os.path.join(OUT, "font_ascii.c"),
                "const unsigned char font_ascii8[FONT_COUNT][8]", ascii8,
                lambda i: "0x%02X %r" % (0x20 + i, chr(0x20 + i)))
    with open(os.path.join(OUT, "font_ascii.c"), "a", encoding="utf-8") as f:
        f.write("\nconst unsigned char font_ascii12[FONT_COUNT][24] = {\n")
        for i, row in enumerate(ascii12):
            f.write("\t{ %s }, /* 0x%02X */\n" % (", ".join("0x%02X" % b for b in row), 0x20 + i))
        f.write("};\n")
    print("ascii table done, brackets repaired:", fixed)

    # --- proportional metrics: left bearing and advance per glyph.
    # Space stays narrow; a single pixel is left between glyphs.
    def metrics(rows, height, cells):
        lb, ad = [], []
        for i, g in enumerate(rows):
            ink_min, ink_max = 999, -1
            for r in range(height):
                if cells == 8:
                    v = g[r]
                    width = 8
                else:
                    v = ((g[r * 2] << 8) | g[r * 2 + 1]) >> 4
                    width = 12
                for x in range(width):
                    if (v >> (width - 1 - x)) & 1:
                        ink_min = min(ink_min, x)
                        ink_max = max(ink_max, x)
            if ink_max < 0:
                lb.append(0)
                ad.append(3 if cells == 8 else 4)     # blank glyph (space)
            else:
                lb.append(ink_min)
                adv = ink_max - ink_min + 2
                ad.append(min(adv, cells))
        return lb, ad

    lb8, adv8 = metrics(ascii8, 8, 8)
    lb12, adv12 = metrics(ascii12, 12, 12)
    with open(os.path.join(OUT, "font_ascii.c"), "a", encoding="utf-8") as f:
        f.write("\nconst unsigned char font_lb8[FONT_COUNT] = { %s };\n" %
                ", ".join(str(v) for v in lb8))
        f.write("const unsigned char font_adv8[FONT_COUNT] = { %s };\n" %
                ", ".join(str(v) for v in adv8))
        f.write("\nconst unsigned char font_lb12[FONT_COUNT] = { %s };\n" %
                ", ".join(str(v) for v in lb12))
        f.write("const unsigned char font_adv12[FONT_COUNT] = { %s };\n" %
                ", ".join(str(v) for v in adv12))
    print("proportional metrics: adv8 avg %.1f, adv12 avg %.1f" %
          (sum(adv8) / len(adv8), sum(adv12) / len(adv12)))

    # --- full CJK glyph data
    cjk8 = [list(f8[BASE + i * 8: BASE + i * 8 + 8]) for i in range(n)]
    cjk12 = [list(f12[BASE + i * 24: BASE + i * 24 + 24]) for i in range(n)]
    write_array(os.path.join(OUT, "font_cjk8.c"),
                "const unsigned char font_cjk8[FONT_GLYPHS][8]", cjk8,
                None)
    write_array(os.path.join(OUT, "font_cjk12.c"),
                "const unsigned char font_cjk12[FONT_GLYPHS][24]", cjk12,
                None)

    # --- Unicode -> glyph index (for UTF-8 files), sorted by codepoint
    pairs = []
    for cp in range(0x20, 0x10000):
        try:
            b = chr(cp).encode("gb2312")
        except (UnicodeEncodeError, ValueError):
            continue
        if len(b) != 2:
            continue
        qu, wei = b[0] - 0xA0, b[1] - 0xA0
        if 1 <= qu <= 94 and 1 <= wei <= 94:
            idx = (qu - 1) * 94 + (wei - 1)
            if idx < n:
                pairs.append((cp, idx))
    pairs.sort()
    print("unicode->glyph pairs:", len(pairs))
    with open(os.path.join(OUT, "gb_map.c"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/mkfont.py - do not edit. */\n")
        f.write('#include "font.h"\n\n')
        f.write("const unsigned short gb_uni[GB_MAP_COUNT] = {\n")
        for i in range(0, len(pairs), 10):
            f.write("\t" + ", ".join("0x%04X" % p[0] for p in pairs[i:i + 10]) + ",\n")
        f.write("};\n\n")
        f.write("const unsigned short gb_idx[GB_MAP_COUNT] = {\n")
        for i in range(0, len(pairs), 10):
            f.write("\t" + ", ".join("0x%04X" % p[1] for p in pairs[i:i + 10]) + ",\n")
        f.write("};\n")
    print("wrote gb_map.c")

    # --- reverse map glyph -> unicode, for saving UTF-8 files
    rev = [0] * n
    for cp, idx in pairs:
        if idx < n:
            rev[idx] = cp
    with open(os.path.join(OUT, "gb_rev.c"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/mkfont.py - do not edit. */\n")
        f.write('#include "font.h"\n\n')
        f.write("const unsigned short gb_rev[FONT_GLYPHS] = {\n")
        for i in range(0, n, 10):
            f.write("\t" + ", ".join("0x%04X" % v for v in rev[i:i + 10]) + ",\n")
        f.write("};\n")
    print("wrote gb_rev.c")

    # --- header
    with open(os.path.join(OUT, "font.h"), "w", encoding="utf-8") as f:
        f.write("#ifndef FXTXT_FONT_H\n#define FXTXT_FONT_H\n\n"
                "#define FONT_FIRST 0x20\n#define FONT_LAST  0x7E\n"
                "#define FONT_COUNT (FONT_LAST - FONT_FIRST + 1)\n"
                "#define FONT_GLYPHS %d\n#define GB_MAP_COUNT %d\n\n"
                "extern const unsigned char font_ascii8[FONT_COUNT][8];\n"
                "extern const unsigned char font_ascii12[FONT_COUNT][24];\n"
                "extern const unsigned char font_cjk8[FONT_GLYPHS][8];\n"
                "extern const unsigned char font_cjk12[FONT_GLYPHS][24];\n"
                "extern const unsigned short gb_uni[GB_MAP_COUNT];\n"
                "extern const unsigned short gb_idx[GB_MAP_COUNT];\n"
                "extern const unsigned short gb_rev[FONT_GLYPHS];\n"
                "extern const unsigned char font_lb8[FONT_COUNT];\n"
                "extern const unsigned char font_adv8[FONT_COUNT];\n"
                "extern const unsigned char font_lb12[FONT_COUNT];\n"
                "extern const unsigned char font_adv12[FONT_COUNT];\n\n"
                "#endif\n" % (n, len(pairs)))
    print("wrote font.h")


if __name__ == "__main__":
    main()
