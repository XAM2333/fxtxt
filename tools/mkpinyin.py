"""Generate a pinyin -> GB2312 character table for the FXTXT input method.

Every GB2312 hanzi (qu 16..87) is mapped to its toneless pinyin with pypinyin,
grouped by syllable and emitted in GB2312 order (level-1 characters first, which
is also the commonness order for candidates).

Output: work/fxtxt/src/pinyin.c (+ declarations appended to font.h)
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "pylib"))
from pypinyin import pinyin, Style  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "work", "fxtxt", "src")

groups = {}
skipped = 0
for qu in range(16, 88):
    for wei in range(1, 95):
        try:
            ch = bytes([qu + 0xA0, wei + 0xA0]).decode("gb2312")
        except UnicodeDecodeError:
            continue
        res = pinyin(ch, style=Style.NORMAL, heteronym=True, errors=lambda x: [None])
        if not res or not res[0]:
            skipped += 1
            continue
        glyph = (qu - 1) * 94 + (wei - 1)
        seen = set()
        primary = (res[0][0] or '').lower()
        for py in res[0]:
            if not py or not py.isalpha() or len(py) > 6:
                continue
            key = py.lower()
            if key in seen:
                continue
            seen.add(key)
            # (rank, glyph): rank 0 = the character's usual reading, 1 = rare
            groups.setdefault(key, []).append((0 if key == primary else 1, glyph))

syllables = sorted(groups)
total = sum(len(v) for v in groups.values())
print("syllables: %d, characters: %d, skipped: %d" % (len(syllables), total, skipped))

names = bytearray()
offs = [0]
for s in syllables:
    names.extend(s.encode("ascii"))
    names.append(0)
    offs.append(len(names))

chars = []
starts = [0]
for s in syllables:
    ordered = [g for _, g in sorted(groups[s])]   # usual reading first, then GB order
    chars.extend(ordered)
    starts.append(len(chars))

with open(os.path.join(OUT, "pinyin.c"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/mkpinyin.py - do not edit. */\n")
    f.write('#include "pinyin.h"\n\n')
    f.write("const unsigned short py_off[PY_COUNT + 1] = {\n")
    for i in range(0, len(offs), 12):
        f.write("\t" + ", ".join(str(v) for v in offs[i:i + 12]) + ",\n")
    f.write("};\n\n")
    f.write("const char py_names[] =\n")
    line = ""
    for b in names:
        c = chr(b)
        if c == "\0":
            line += "\\0"
        elif c == '"' or c == "\\":
            line += "\\" + c
        else:
            line += c
        if len(line) >= 70:
            f.write('\t"%s"\n' % line)
            line = ""
    if line:
        f.write('\t"%s"\n' % line)
    f.write(";\n\n")
    f.write("const unsigned short py_start[PY_COUNT + 1] = {\n")
    for i in range(0, len(starts), 12):
        f.write("\t" + ", ".join(str(v) for v in starts[i:i + 12]) + ",\n")
    f.write("};\n\n")
    f.write("const unsigned short py_glyph[PY_CHARS] = {\n")
    for i in range(0, len(chars), 12):
        f.write("\t" + ", ".join(str(v) for v in chars[i:i + 12]) + ",\n")
    f.write("};\n")

with open(os.path.join(OUT, "pinyin.h"), "w", encoding="utf-8") as f:
    f.write("#ifndef FXTXT_PINYIN_H\n#define FXTXT_PINYIN_H\n\n")
    f.write("#define PY_COUNT %d\n#define PY_CHARS %d\n#define PY_NAME_LEN %d\n\n"
            % (len(syllables), len(chars), len(names)))
    f.write("extern const unsigned short py_off[PY_COUNT + 1];\n")
    f.write("extern const char py_names[];\n")
    f.write("extern const unsigned short py_start[PY_COUNT + 1];\n")
    f.write("extern const unsigned short py_glyph[PY_CHARS];\n\n")
    f.write("#endif\n")
print("wrote pinyin.c / pinyin.h")
