"""Generate 7x7 row bitmaps for the list icons from folder.png / file.png.

The two PNGs live in the repository root and are drawn by the user. Each file is
thresholded and packed into one byte per row (bit 6 = leftmost pixel).
"""
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pylib"))
from PIL import Image  # noqa: E402

SRC = {"folder": "folder.png", "file": "file.png"}
OUT_C = os.path.join("work", "fxtxt", "src", "icons.c")
OUT_H = os.path.join("work", "fxtxt", "src", "icons.h")


def rows_of(path):
    im = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    g = Image.alpha_composite(bg, im).convert("L")
    w, h = g.size
    if w > 7 or h > 7:
        g = g.resize((7, 7), Image.NEAREST)
        w = h = 7
    out = []
    for y in range(h):
        byte = 0
        for x in range(w):
            if g.getpixel((x, y)) < 128:
                byte |= 1 << (6 - x)
        out.append(byte)
    return out, w, h


def emit():
    data = {}
    for name, path in SRC.items():
        if not os.path.exists(path):
            print("missing", path)
            return 1
        rows, w, h = rows_of(path)
        data[name] = (rows, w, h)

    with io.open(OUT_C, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/mkicons.py from folder.png / file.png. */\n")
        f.write('#include "icons.h"\n\n')
        for name, (rows, w, h) in data.items():
            f.write("unsigned char const icon_%s_rows[] = { %s };\n"
                    % (name, ", ".join("0x%02X" % b for b in rows)))
            f.write("int const icon_%s_w = %d, icon_%s_h = %d;\n\n"
                    % (name, w, name, h))

    with io.open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/mkicons.py. */\n")
        f.write("#ifndef FXTXT_ICONS_H\n#define FXTXT_ICONS_H\n\n")
        for name in data:
            f.write("extern unsigned char const icon_%s_rows[];\n" % name)
            f.write("extern int const icon_%s_w, icon_%s_h;\n" % (name, name))
        f.write("\n#endif\n")

    for name, (rows, w, h) in data.items():
        print(name, w, "x", h, " ".join("%02X" % b for b in rows))
    return 0


sys.exit(emit())
